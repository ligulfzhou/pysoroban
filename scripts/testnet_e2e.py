def truncate_hash(value: str) -> str:
    return value[:8] + "\u2026" + value[-6:]


def transaction_hashes(text: str) -> list[str]:
    return TX_URL.findall(text)


def wasm_hash(stdout: str) -> str:
    for line in reversed(stdout.splitlines()):
        stripped = line.strip()
        if HEX64.fullmatch(stripped):
            return stripped
    raise ValueError("upload did not print a wasm hash")


def contract_id(stdout: str) -> str:
    matches = CONTRACT_ID.findall(stdout)
    if not matches:
        raise ValueError("deploy did not print a contract id")
    return matches[-1]


def invoke_result(stdout: str) -> str:
    data = []
    for line in stdout.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped[0] in "ℹ✅🔗🌎❌📅":
            continue
        if stripped.startswith(("error:", "HostError", "Event log")):
            continue
        data.append(stripped)
    return data[-1] if data else ""


def render_manifest(source_account: str, contracts: dict) -> str:
    lines = [
        "// Generated by scripts/testnet_e2e.py. Public testnet records only.",
        "export const SOURCE_ACCOUNT =",
        '  "{}";'.format(source_account),
        "",
        "export const testnetContracts = {",
    ]
    for json_key, web_key in WEB_KEYS.items():
        item = contracts[json_key]
        lines.append("  {}: {{".format(web_key))
        lines.append('    id: "{}",'.format(item["contract_id"]))
        lines.append('    hash: "{}",'.format(truncate_hash(item["wasm_hash"])))
        lines.append('    transaction: "{}",'.format(item["deploy_transaction"]))
        lines.append("  },")
    lines.append("} as const;")
    lines.append("")
    return "\n".join(lines)


