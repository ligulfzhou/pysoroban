def stellar_bin() -> str:
    found = shutil.which("stellar")
    if found:
        return found
    candidate = Path.home() / ".local" / "bin" / "stellar"
    if candidate.is_file():
        return str(candidate)
    raise SystemExit("stellar CLI is not on PATH. Install stellar-cli 25.2.0 or newer.")


def run(args: list[str], *, check: bool = True) -> subprocess.CompletedProcess[str]:
    print("+", " ".join(args), flush=True)
    proc = subprocess.run(args, text=True, capture_output=True)
    if proc.stdout:
        sys.stdout.write(proc.stdout)
        if not proc.stdout.endswith("\n"):
            sys.stdout.write("\n")
    if proc.stderr:
        sys.stderr.write(proc.stderr)
        if not proc.stderr.endswith("\n"):
            sys.stderr.write("\n")
    if check and proc.returncode != 0:
        raise SystemExit(proc.returncode)
    return proc


def ensure_identity(stellar: str, identity: str | None, fund: bool) -> tuple[str, str]:
    if identity is None:
        identity = "pysoroban-e2e"
        fund = True
    listed = run([stellar, "keys", "ls"], check=False)
    known = identity in listed.stdout.split()
    if not known:
        generate = [stellar, "keys", "generate", identity, "--network", "testnet"]
        if fund:
            generate.append("--fund")
        run(generate)
    elif fund:
        run([stellar, "keys", "fund", identity, "--network", "testnet"])
    address = run([stellar, "keys", "address", identity]).stdout.strip().splitlines()[-1].strip()
    if not address.startswith("G"):
        raise SystemExit("unexpected public key {!r}".format(address))
    return identity, address


def build_wasm(source: str, destination: Path) -> None:
    run([sys.executable, "-m", "pysoroban", "build", source, "-o", str(destination)])


def deploy_one(stellar: str, identity: str, wasm: Path) -> dict:
    uploaded = run([
        stellar, "--no-cache", "contract", "upload",
        "--wasm", str(wasm),
        "--source", identity,
        "--network", "testnet",
    ])
    deployed = run([
        stellar, "--no-cache", "contract", "deploy",
        "--wasm", str(wasm),
        "--source", identity,
        "--network", "testnet",
    ])
    upload_text = uploaded.stdout + uploaded.stderr
    deploy_text = deployed.stdout + deployed.stderr
    upload_ids = transaction_hashes(upload_text)
    deploy_ids = transaction_hashes(deploy_text)
    return {
        "wasm_hash": wasm_hash(uploaded.stdout),
        "upload_transaction": upload_ids[-1] if upload_ids else "",
        "contract_id": contract_id(deployed.stdout),
        "deploy_transaction": deploy_ids[-1] if deploy_ids else "",
    }


def substitute(args: list[str], env: dict[str, str]) -> list[str]:
    rendered = []
    for arg in args:
        for key, value in env.items():
            arg = arg.replace("{" + key + "}", value)
        rendered.append(arg)
    return rendered


def invoke(stellar: str, identity: str, contract: str, call: dict, env: dict[str, str]) -> dict:
    send = call.get("send", "no")
    command = [
        stellar, "--no-cache", "contract", "invoke",
        "--id", contract,
        "--source", identity,
        "--network", "testnet",
        "--send", send,
        "--",
        call["fn"],
        *substitute(call.get("args", []), env),
    ]
    proc = run(command, check=False)
    text = proc.stdout + proc.stderr
    record = {"exit_code": proc.returncode}
    if "error" in call:
        if proc.returncode == 0 or call["error"] not in text:
            raise SystemExit(
                "expected failure {!r} from {} but got exit {}:\n{}".format(
                    call["error"], call["fn"], proc.returncode, text
                )
            )
        record["error"] = call["error"]
        return record
    if proc.returncode != 0:
        raise SystemExit("{} failed:\n{}".format(call["fn"], text))
    result = invoke_result(proc.stdout)
    if "expect" in call and result != call["expect"]:
        raise SystemExit(
            "{} returned {!r}, expected {!r}".format(call["label"], result, call["expect"])
        )
    if "event" in call and call["event"] not in text:
        raise SystemExit("{} did not publish {!r}:\n{}".format(call["label"], call["event"], text))
    if "expect" in call:
        record["result"] = result
    txs = transaction_hashes(text)
    if txs:
        record["transaction"] = txs[-1]
    if "event" in call:
        record["event"] = call["event"]
    return record


def interface_contains(stellar: str, contract: str, needles: list[str]) -> None:
    proc = run([
        stellar, "contract", "info", "interface",
        "--id", contract,
        "--network", "testnet",
    ])
    text = proc.stdout + proc.stderr
    missing = [needle for needle in needles if needle not in text]
    if missing:
        raise SystemExit("contract spec missing {}: \n{}".format(missing, text))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--identity", default=os.environ.get("STELLAR_IDENTITY"))
    parser.add_argument("--fund", action="store_true", help="friendbot-fund the identity")
    parser.add_argument("--output", type=Path, default=ROOT / "deployments" / "testnet.json")
    parser.add_argument("--manifest", type=Path, default=ROOT / "web" / "app" / "testnet-manifest.ts")
    args = parser.parse_args(argv)

    stellar = stellar_bin()
    version = run([stellar, "--version"]).stdout.strip().splitlines()[0]
    identity, source = ensure_identity(stellar, args.identity, args.fund)
    print("source account", source, flush=True)

    env = {"source": source}
    contracts: dict[str, dict] = {}
    build_dir = Path(os.environ.get("TMPDIR", "/tmp")) / "pysoroban-testnet-e2e"
    build_dir.mkdir(parents=True, exist_ok=True)

    for item in _catalog():
        wasm = build_dir / (item["key"] + ".wasm")
        build_wasm(str(ROOT / item["source"]), wasm)
        deployed = deploy_one(stellar, identity, wasm)
        env[item["key"]] = deployed["contract_id"]
        verified = {}
        events = []
        errors = []
        for call in item["calls"]:
            target_key = call.get("contract", item["key"])
            outcome = invoke(stellar, identity, env[target_key], call, env)
            if "result" in outcome:
                verified[call["label"]] = outcome["result"]
            if "error" in outcome:
                errors.append({"call": call["label"], "error": outcome["error"]})
            if outcome.get("transaction"):
                verified[call["label"] + " transaction"] = outcome["transaction"]
            if outcome.get("event"):
                events.append({"call": call["label"], "match": outcome["event"]})
        if item.get("interface"):
            interface_contains(stellar, deployed["contract_id"], item["interface"])
        deployed["source"] = item["source"]
        deployed["verified_calls"] = verified
        if events:
            deployed["verified_events"] = events
        if errors:
            deployed["verified_errors"] = errors
        contracts[item["key"]] = deployed

    record = {
        "network": "testnet",
        "network_passphrase": NETWORK_PASSPHRASE,
        "verified_at": "2026-10-21",
        "protocol": 25,
        "cli": version,
        "source_account": source,
        "contracts": contracts,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    args.manifest.write_text(render_manifest(source, contracts), encoding="utf-8")
    print("wrote", args.output)
    print("wrote", args.manifest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
